function native() {
  const saved = new Map(), states = [], requests = [], credential = {
    deviceId: 'device-1', actorId: 23, serverOrigin: origin
  };
  const attempts = new DashboardRemoteAttempts({
    state: { begin: async id => states.push(['begin', id]), complete: async id => states.push(['complete', id]),
      read: async () => ({ pending: states.filter(item => item[0] === 'begin').map(item => item[1]) }) },
    metadata: { write: async (key, value) => saved.set(key, value), read: async key => saved.get(key) },
    credential: async () => credential,
    request: async request => {
      requests.push(request); return { format: 1, id: request.id, device_id: credential.deviceId, actor_id: credential.actorId,
        method: request.method, path: request.path, status: request.action === 'reserve' ? 'ready' : 'committed', capability: 'a'.repeat(64) };
    }
  });
  return { attempts, saved, states, requests };
}

test('native checkbox and featured-ordering support uses exact POST paths and excludes operating/global controls', () => {
  const { attempts } = native();
  for (const route of writeRoutes) {
    const url = origin + '/admin/' + route + '/27?page=5';
    assert.equal(attempts.supported({ url, method: 'POST' }), true);
    for (const method of ['GET', 'HEAD', 'PUT', 'PATCH', 'DELETE']) assert.equal(attempts.supported({ url, method }), false);
    for (const id of ['0', '01', '-1', '99999999999999999999', '27/', '27/extra'])
      assert.equal(attempts.supported({ url: origin + '/admin/' + route + '/' + id, method: 'POST' }), false);
  }
  for (const url of ['/admin/updateStatus/27', '/admin/resturantControl', '/admin/resturantControl/27', '/admin/resturants/27'])
    assert.equal(attempts.supported({ url: origin + url, method: 'POST' }), false);
  assert.equal(attempts.supported({url:origin+'/admin/resturantControl',method:'GET'}),false);
});

test('native checkbox and ordering writes reserve their actual method/path and settle with the same operation', async () => {
  for (const route of writeRoutes) {
    const env = native(), url = origin + '/admin/' + route + '/27?page=5';
    const headers = await env.attempts.begin(attemptId, { url, method: 'POST' });
    assert.deepEqual(headers, { 'X-Fasakhansta-Remote-Attempt': attemptId, 'X-Fasakhansta-Remote-Capability': 'a'.repeat(64) });
    const record = env.saved.get('remote-attempts/' + attemptId);
    assert.equal(record.method, 'POST'); assert.equal(record.path, '/admin/' + route + '/27');
    assert.deepEqual(env.requests, [{ action: 'reserve', id: attemptId, method: 'POST', path: record.path }]);
    await env.attempts.complete(attemptId);
    assert.deepEqual(env.states, [['begin', attemptId], ['complete', attemptId]]);
    assert.deepEqual(env.requests[1], { action: 'settle', id: attemptId, method: 'POST', path: record.path });
    assert.equal(env.saved.get('remote-attempts/' + attemptId).receipt.status, 'committed');
  }
});

test('a lost flag HTTP reply remains bound for native recovery instead of completing provisionally', async () => {
  const env = native(), path = '/admin/resturantchangeStatus/28';
  await env.attempts.begin(attemptId, { url: origin + path, method: 'POST' });
  env.attempts.failed(attemptId); assert.deepEqual(env.states, [['begin', attemptId]]);
  await env.attempts.recover();
  assert.deepEqual(env.requests[1], { action: 'settle', id: attemptId, method: 'POST', path });
  assert.deepEqual(env.states, [['begin', attemptId], ['complete', attemptId]]);
});

