// Execute the actual renderer against form behavior needed by the original
// checkbox's this.form.submit(); no submit event is generated by this method.
function browser({ local = true, prepared = true, bridge = true, statusFails = false, forms = [], spaReady = false, pagePresent = true } = {}) {
  const listeners = new Map(), observers = [], issued = [], submitted = [];
  class Form {
    constructor(action, method = 'post', fields = []) {
      this.action = new URL(action, origin).href; this.method = method;
      this.fields = fields.map(field => ({ ...field })); this.dataset = {};
    }
    querySelector(selector) {
      const match = /^\[name="([^"]+)"\]$/.exec(selector);
      return match ? this.fields.find(field => field.name === match[1]) || null : null;
    }
    append(field) { this.fields.push(field); }
    hasAttribute(name) { return Boolean(this.attributes?.has(name)); }
    submit() { submitted.push({ action: this.action, fields: this.fields.map(field => ({ ...field })) }); }
  }
  const all = forms.map(values => new Form(...values));
  const document = {
    body: { dataset: { dashboardLocal: local ? '1' : '0', dashboardRemoteAttempts: '1' } },
    documentElement: {}, querySelectorAll: selector => selector === 'form' ? all : [],
    querySelector: selector => selector === '[data-dashboard-page]' && spaReady && pagePresent ? {} : null, createElement: tag => { assert.equal(tag, 'input'); return {}; },
    addEventListener: (name, fn) => listeners.set(name, fn)
  };
  const window = bridge ? { FasakhanstaDesktop: { status: async () => {
    if (statusFails) throw Error('unavailable'); return { prepared };
  } } } : {};
  window.DashboardSPA = { ready: () => spaReady };
  const context = vm.createContext({ document, window, HTMLFormElement: Form, URL, URLSearchParams,
    location: { href: origin + '/admin/resturants?page=3', origin },
    MutationObserver: class { constructor(fn) { this.fn = fn; observers.push(this); } observe() {} },
    crypto: { randomUUID: () => { const id = 'f2020202-2020-4020-8020-' + String(issued.length + 1).padStart(12, '0'); issued.push(id); return id; } },
    sessionStorage: { getItem: () => null, setItem: () => {} }
  });
  return { all, Form, listeners, observers, issued, submitted,
    execute: () => vm.runInContext(renderer, context),
    mutate: () => observers.forEach(observer => observer.fn()) };
}

test('original automatic checkbox forms have distinct UUIDs before native form.submit, without a submit event', async () => {
  const env = browser({ forms: routes.map((route, i) => [
    '/admin/' + route + '/17?page=3', 'post', [{ name: '_token', value: 'original-csrf' },
      { type: 'checkbox', name: i ? 'under_contract' : 'is_featured', value: 'on', checked: Boolean(i) }]
  ]) });
  await env.execute();
  for (const form of env.all) form.submit();
  assert.equal(env.submitted.length, 2); assert.equal(env.issued.length, 2);
  assert.notEqual(env.all[0].querySelector('[name="_desktop_command"]').value,
    env.all[1].querySelector('[name="_desktop_command"]').value);
  for (const [i, submission] of env.submitted.entries()) {
    assert.ok(submission.fields.some(field => field.name === '_desktop_command' && field.value === env.issued[i]));
    assert.equal(submission.action, origin + '/admin/' + routes[i] + '/17?page=3');
    assert.deepEqual(submission.fields.filter(field => field.name !== '_desktop_command'), [
      { name: '_token', value: 'original-csrf' },
      { type: 'checkbox', name: i ? 'under_contract' : 'is_featured', value: 'on', checked: Boolean(i) }
    ]);
  }
});

