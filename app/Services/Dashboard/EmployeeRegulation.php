    /** Acceptance status for one employee row, without any file or actor details. */
    public static function status(object|array $employee): array
    {
        $employee=(object)$employee;
        $version=$employee->regulation_version??null;
        $accepted=is_string($version)&&$version!==''&&!empty($employee->regulation_accepted_at)&&!empty($employee->regulation_accepted_by);
        return ['accepted'=>$accepted,'current'=>$accepted&&$version===self::VERSION,'version'=>$version,
            'accepted_at'=>$employee->regulation_accepted_at??null,'current_version'=>self::VERSION];
    }
