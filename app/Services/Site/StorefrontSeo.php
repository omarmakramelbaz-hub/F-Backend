    }

    public static function indexMetadata(): array
    {
        return self::metadata('منتجات فسخانستا | فسيخ ورنجة وسردين وبطارخ',
            'اكتشف دليل منتجات فسخانستا: الفسيخ والرنجة والسردين والبطارخ. تعرف على اختياراتك ثم حدد عنوانك لعرض منيو وأسعار المتجر الذي يخدمك.', '/products', self::schema('products'));
    }

    public static function categoryMetadata(string $slug): ?array
    {
        $category = self::category($slug);
        return $category ? self::metadata($category['title'], $category['description'], '/products/' . $slug, self::schema($slug)) : null;
    }

    private static function metadata(string $title, string $description, string $path, array $schema): array
    {
        return ['title' => $title, 'description' => $description, 'canonical' => self::url($path),
            'image' => self::url('/storefront/hero.webp'), 'schema' => $schema];
    }

    public static function homeSchema(): array
    {
        return ['@context' => 'https://schema.org', '@graph' => [
            ['@type' => 'Organization', '@id' => self::url() . '#organization', 'name' => 'فسخانستا',
                'alternateName' => 'Fasakhansta', 'url' => self::url(),
                'logo' => self::url('/dashboard/branding/fasakhansta-logo-transparent.png')],
            ['@type' => 'WebSite', '@id' => self::url() . '#website', 'url' => self::url(),
                'name' => 'فسخانستا', 'alternateName' => 'Fasakhansta', 'inLanguage' => 'ar-EG',
                'publisher' => ['@id' => self::url() . '#organization']],
        ]];
    }

    public static function schema(string $page): array
    {
        $category = $page === 'products' ? null : self::category($page);
        if ($page !== 'products' && !$category) {
            return [];
        }
        $url = self::url('/products' . ($category ? '/' . $page : ''));
        $breadcrumbs = [
            ['@type' => 'ListItem', 'position' => 1, 'name' => 'الرئيسية', 'item' => self::url()],
            ['@type' => 'ListItem', 'position' => 2, 'name' => 'المنتجات', 'item' => self::url('/products')],
        ];
        if ($category) {
            $breadcrumbs[] = ['@type' => 'ListItem', 'position' => 3, 'name' => $category['name'], 'item' => $url];
        }
        $collection = ['@type' => 'CollectionPage', '@id' => $url . '#page', 'url' => $url,
            'name' => $category ? $category['title'] : 'منتجات فسخانستا',
            'description' => $category ? $category['description'] : 'دليل الفسيخ والرنجة والسردين والبطارخ من فسخانستا.',
            'inLanguage' => 'ar-EG', 'isPartOf' => ['@id' => self::url() . '#website'],
            'breadcrumb' => ['@id' => $url . '#breadcrumb']];
        if ($category) {
            $collection['about'] = ['@type' => 'Thing', 'name' => $category['name']];
        } else {
            $items = [];
            foreach (self::categories() as $slug => $item) {
                $items[] = ['@type' => 'ListItem', 'position' => count($items) + 1,
                    'name' => $item['name'], 'url' => self::url('/products/' . $slug)];
            }
            $collection['mainEntity'] = ['@type' => 'ItemList', 'itemListElement' => $items];
        }
        return ['@context' => 'https://schema.org', '@graph' => [
            $collection, ['@type' => 'BreadcrumbList', '@id' => $url . '#breadcrumb', 'itemListElement' => $breadcrumbs],
        ]];
    }

    public static function sitemapXml(): string
    {
        $paths = ['', '/products'];
        foreach (array_keys(self::categories()) as $slug) {
            $paths[] = '/products/' . $slug;
        }
        $xml = '<?xml version="1.0" encoding="UTF-8"?>' . "\n";
        $xml .= '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">' . "\n";
        foreach ($paths as $path) {
            $xml .= '  <url><loc>' . htmlspecialchars(self::url($path), ENT_XML1 | ENT_QUOTES, 'UTF-8') . '</loc></url>' . "\n";
        }
        return $xml . '</urlset>' . "\n";
    }
